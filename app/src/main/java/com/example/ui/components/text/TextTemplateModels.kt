fun TextTemplateItem.toTextClips(
  timelineStartMs: Long,
  durationMs: Long = 3000L,
  customTextOverride: String? = null
): List<com.example.domain.model.TextClip> {
  val clips = mutableListOf<com.example.domain.model.TextClip>()
  val primaryConfig = toPrimaryLayerConfig()
  clips.add(primaryConfig.toTextClip(timelineStartMs, durationMs, customTextOverride))

  secondaryLayers.forEach { sec ->
    clips.add(sec.toTextClip(timelineStartMs, durationMs, null))
  }
  return clips
}

